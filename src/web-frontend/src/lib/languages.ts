type LanguageDraft = Omit<
  LanguageProfile,
  "color" | "mark" | "overview" | "related" | "tagline"
> & {
  mark?: string;
  overview?: string;
  related?: string[];
  tagline?: string;
};

const categoryColors: Record<LanguageCategory, string> = {
  系統與效能: "bg-orange-50 text-orange-700",
  "Web 與全端": "bg-blue-50 text-blue-700",
  "資料科學與 AI": "bg-violet-50 text-violet-700",
  雲端與分散式: "bg-cyan-50 text-cyan-700",
  晶片設計: "bg-teal-50 text-teal-700",
  應用程式與行動: "bg-indigo-50 text-indigo-700",
  遊戲與互動: "bg-rose-50 text-rose-700",
  資料庫與查詢: "bg-emerald-50 text-emerald-700",
};

function createLanguageProfile(draft: LanguageDraft): LanguageProfile {
  return {
    ...draft,
    mark: draft.mark ?? draft.name.slice(0, 2),
    color: categoryColors[draft.category],
    tagline: draft.tagline ?? draft.description,
    overview:
      draft.overview ??
      `${draft.name} 常用於${draft.useCases.join("、")}。選擇時可依團隊經驗、工具支援和部署需求評估。`,
    related: draft.related ?? [],
  };
}

